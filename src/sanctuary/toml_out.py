"""Serialize a World as a Unbodysoma scenario TOML.

The writer is the compatibility contract: Unbodysoma's loader (ADR-0008)
rejects unknown keys, so the emitted key set must match its ``_FOOD`` /
``_WATER`` / ``_SHELTER`` / ``_HAZARD`` / ``_WORLD`` allow-lists exactly.
Permanent hazards omit ``start`` / ``end`` / ``every`` (their defaults are
infinite and TOML has no infinity literal).

Floats use a fixed formatting recipe so the same world always serializes to
the same bytes — golden tests pin this.
"""

from __future__ import annotations

from math import isfinite

from . import __version__
from .world import World

# Adapter capability (DESIGN §4): the systems this adapter can express.
# Anything outside raises loudly — silent omission is forbidden. The first
# real use arrives with seasonal dynamics (Phase 3): it lands in core+JSON
# first, and TOML raises until Unbodysoma's key set catches up (ADR-0010).
TOML_SYSTEMS = frozenset({"food", "water", "shelter", "hazard-permanent", "hazard-patrol"})


def _check_capability(world: World) -> None:
    unsupported = set(world.systems) - TOML_SYSTEMS
    if unsupported:
        raise ValueError(
            f"TOML adapter cannot express systems {sorted(unsupported)}; emit a JSON artifact for this archetype"
        )


def _f(v: float) -> str:
    """Format a float deterministically: 6 decimals, trailing zeros trimmed."""
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return s if s else "0"


def scenario_toml(
    world: World,
    *,
    duration_h: float = 72.0,
    base_dt: float = 0.05,
    organism_seed: int | None = None,
) -> str:
    """Render ``world`` as a complete, runnable Unbodysoma scenario file."""
    _check_capability(world)
    seed = world.seed if organism_seed is None else organism_seed
    stamp = f"sanctuary-g-code v{__version__} — preset={world.preset}@{world.preset_version}, seed={world.seed}"
    lines: list[str] = [
        f"# Generated by {stamp}",
        f"# Reproduce: sanctuary --seed {world.seed} --preset {world.preset} --out <this file>",
        "",
        "[scenario]",
        f'name = "{world.name}"',
        (
            f"description = \"Generated world '{world.name}' ({len(world.food)} patches, "
            f'{len(world.water)} springs, {len(world.hazards)} hazards)"'
        ),
        f"duration_h = {_f(duration_h)}",
        f"seed = {seed}",
        f"base_dt = {_f(base_dt)}",
        "",
        "[organism]",
        'preset = "grid"',
        "",
        "[world]",
        f"width = {_f(world.width)}",
        f"height = {_f(world.height)}",
        f"start = [{_f(world.start[0])}, {_f(world.start[1])}]",
    ]
    for patch in world.food:
        lines += ["", "[[world.food]]", f"x = {_f(patch.x)}", f"y = {_f(patch.y)}"]
        if patch.capacity != 1.0:
            lines.append(f"capacity = {_f(patch.capacity)}")
        lines.append(f"regrow_per_hour = {_f(patch.regrow_per_hour)}")
    for spring in world.water:
        lines += ["", "[[world.water]]", f"x = {_f(spring.x)}", f"y = {_f(spring.y)}"]
    for shelter in world.shelters:
        lines += [
            "",
            "[[world.shelters]]",
            f"x = {_f(shelter.x)}",
            f"y = {_f(shelter.y)}",
            f"radius = {_f(shelter.radius)}",
            f"insulation = {_f(shelter.insulation)}",
        ]
    for hazard in world.hazards:
        lines += [
            "",
            "[[world.hazards]]",
            f"x = {_f(hazard.x)}",
            f"y = {_f(hazard.y)}",
            f"radius = {_f(hazard.radius)}",
            f"strength = {_f(hazard.strength)}",
        ]
        if isfinite(hazard.end):
            lines += [
                f"start = {_f(hazard.start)}",
                f"end = {_f(hazard.end)}",
                f"every = {_f(hazard.every)}",
            ]
    lines += [
        "",
        "[observe]",
        "record_every = 60.0",
        "monitor = true",
        "monitor_every = 10.0",
        'halt_on = "critical"',
        "",
    ]
    return "\n".join(lines)
